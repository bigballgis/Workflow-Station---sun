package com.developer.component.impl;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * A release must carry the parent table of every foreign key on the relation tables its forms bind:
 * activation (CatalogSnapshotReader.completeFormBindings) rejects a snapshot whose FK parent is missing.
 */
class RelationTableStructureReferenceClosureTest {

    private JdbcTemplate jdbc;
    private RelationTableStructurePortability portability;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:rt_closure_" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE rt_table_definitions (id BIGINT PRIMARY KEY, table_name VARCHAR(100), "
                + "display_name VARCHAR(100), description VARCHAR(255))");
        jdbc.execute("CREATE TABLE rt_field_definitions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, table_id BIGINT, "
                + "field_name VARCHAR(100), data_type VARCHAR(30), length INT, precision_value INT, scale INT, "
                + "nullable BOOLEAN, is_primary_key BOOLEAN, default_value VARCHAR(100), display_name VARCHAR(100), "
                + "is_foreign_key BOOLEAN, ref_table_id BIGINT, ref_primary_key_fields VARCHAR(255), "
                + "pk_generation_json VARCHAR(255), fk_display_mode VARCHAR(30), lookup_config VARCHAR(255), "
                + "sort_order INT, is_computed BOOLEAN, computed_field_json VARCHAR(255))");
        portability = new RelationTableStructurePortability(jdbc, new ObjectMapper());
    }

    private void table(long id, String name) {
        jdbc.update("INSERT INTO rt_table_definitions (id, table_name, display_name) VALUES (?, ?, ?)", id, name, name);
        jdbc.update("INSERT INTO rt_field_definitions (table_id, field_name, data_type, is_primary_key, is_foreign_key, "
                + "sort_order) VALUES (?, 'id', 'VARCHAR', true, false, 0)", id);
    }

    private void foreignKey(long tableId, String field, long refTableId) {
        jdbc.update("INSERT INTO rt_field_definitions (table_id, field_name, data_type, is_primary_key, is_foreign_key, "
                + "ref_table_id, ref_primary_key_fields, sort_order) VALUES (?, ?, 'VARCHAR', false, true, ?, '[\"id\"]', 1)",
                tableId, field, refTableId);
    }

    @Test
    void exportsEveryRelationTableReachableThroughForeignKeys() {
        table(1, "meeting_room");
        table(2, "building");
        table(3, "region");
        table(4, "unrelated");
        foreignKey(1, "building_id", 2);
        foreignKey(2, "region_id", 3);
        foreignKey(3, "head_office_room", 1); // cycle back to the bound table

        List<Map<String, Object>> tables = portability.exportByIds(List.of(1L));

        assertEquals(List.of("meeting_room", "building", "region"),
                tables.stream().map(t -> t.get("tableName")).toList());
        assertEquals(List.of(1L, 2L, 3L), tables.stream().map(t -> t.get("relationTableId")).toList());
        // Only the bound table is the Function Unit's own; parents travel as references.
        assertEquals(java.util.Arrays.asList(null, true, true),
                tables.stream().map(t -> t.get(RelationTableStructurePortability.REFERENCE_ONLY)).toList());
    }

    @Test
    void aTableBothBoundAndReferencedIsTheFunctionUnitsOwn() {
        table(1, "meeting_room");
        table(2, "building");
        foreignKey(1, "building_id", 2);

        List<Map<String, Object>> tables = portability.exportByIds(List.of(1L, 2L));

        assertEquals(List.of("meeting_room", "building"), tables.stream().map(t -> t.get("tableName")).toList());
        assertEquals(java.util.Arrays.asList(null, null),
                tables.stream().map(t -> t.get(RelationTableStructurePortability.REFERENCE_ONLY)).toList());
    }

    @Test
    void exportsOnlyTheBoundTablesWhenTheyHaveNoForeignKeys() {
        table(1, "meeting_room");
        table(2, "building");

        assertEquals(List.of("meeting_room"),
                portability.exportByIds(List.of(1L)).stream().map(t -> t.get("tableName")).toList());
    }
}
