package com.developer.component.impl;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * Runs the "which Function Units use this table" SQL for real: a table is also used by every Function Unit whose
 * tables reach it through foreign keys, so another Function Unit's dependency keeps one Function Unit's rollback
 * from reshaping it. (FK cycles are verified on PostgreSQL only: H2's recursive UNION does not de-duplicate.)
 */
class RelationTableSharedUsageSqlTest {

    private JdbcTemplate jdbc;
    private RelationTableStructurePortability portability;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:rt_usage_" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1"));
        jdbc.execute("CREATE TABLE rt_table_definitions (id BIGINT PRIMARY KEY, table_name VARCHAR(100), "
                + "display_name VARCHAR(100), description VARCHAR(255), status VARCHAR(20), current_version INT, "
                + "updated_at TIMESTAMP, updated_by VARCHAR(100))");
        jdbc.execute("CREATE TABLE rt_field_definitions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "table_id BIGINT, field_name VARCHAR(100), data_type VARCHAR(30), length INT, precision_value INT, "
                + "scale INT, nullable BOOLEAN, is_primary_key BOOLEAN, default_value VARCHAR(100), "
                + "display_name VARCHAR(100), is_foreign_key BOOLEAN, ref_table_id BIGINT, ref_primary_key_fields JSON, "
                + "pk_generation_json JSON, fk_display_mode VARCHAR(30), lookup_config JSON, sort_order INT, "
                + "is_computed BOOLEAN, computed_field_json JSON)");
        jdbc.execute("CREATE TABLE sys_function_units (id VARCHAR(64) PRIMARY KEY, code VARCHAR(100))");
        jdbc.execute("CREATE TABLE rt_table_function_units (id VARCHAR(64) PRIMARY KEY, relation_table_id BIGINT, "
                + "function_unit_id VARCHAR(64))");
        jdbc.update("INSERT INTO sys_function_units (id, code) VALUES ('rel-y', 'fu-y'), ('rel-x', 'fu-x')");
        portability = new RelationTableStructurePortability(jdbc, new ObjectMapper());
    }

    private void table(long id, String name, String... columns) {
        jdbc.update("INSERT INTO rt_table_definitions (id, table_name, display_name, status, current_version) "
                + "VALUES (?, ?, ?, 'DEPLOYED', 1)", id, name, name);
        for (int i = 0; i < columns.length; i++) {
            jdbc.update("INSERT INTO rt_field_definitions (table_id, field_name, data_type, is_primary_key, "
                    + "is_foreign_key, sort_order, is_computed) VALUES (?, ?, 'VARCHAR', ?, false, ?, false)",
                    id, columns[i], i == 0, i);
        }
    }

    private void foreignKey(long tableId, long refTableId) {
        jdbc.update("INSERT INTO rt_field_definitions (table_id, field_name, data_type, is_primary_key, "
                + "is_foreign_key, ref_table_id, sort_order, is_computed) VALUES (?, 'parent_code', 'VARCHAR', false, "
                + "true, ?, 9, false)", tableId, refTableId);
    }

    private void link(long tableId, String release) {
        jdbc.update("INSERT INTO rt_table_function_units (id, relation_table_id, function_unit_id) VALUES (?, ?, ?)",
                release + "-" + tableId, tableId, release);
    }

    private List<String> columnsOf(long tableId) {
        return jdbc.queryForList("SELECT field_name FROM rt_field_definitions WHERE table_id = ? ORDER BY sort_order",
                String.class, tableId);
    }

    /** fu-y rolls back to a version of "parent" that predates its "added" column. */
    private void rollBackParentAsY() {
        portability.importAll(List.of(Map.of("tableName", "parent", "displayName", "parent", "fields",
                List.of(Map.of("fieldName", "code", "dataType", "VARCHAR", "isPrimaryKey", true, "sortOrder", 0)))),
                "tester", "fu-y");
    }

    @Test
    void anotherFunctionUnitReachingTheTableThroughForeignKeysKeepsItsColumns() {
        table(1, "parent", "code", "added");
        link(1, "rel-y");
        table(2, "child", "id");
        foreignKey(2, 1);
        table(3, "grandchild", "id");
        foreignKey(3, 2);
        link(3, "rel-x");

        rollBackParentAsY();

        assertEquals(List.of("code", "added"), columnsOf(1));
        assertEquals("DEPLOYED", jdbc.queryForObject("SELECT status FROM rt_table_definitions WHERE id = 1", String.class));
    }

    @Test
    void foreignKeysFromTablesNoOtherFunctionUnitUsesLeaveItThisFunctionUnitsToRestore() {
        table(1, "parent", "code", "added");
        link(1, "rel-y");
        table(2, "child", "id");
        foreignKey(2, 1);

        rollBackParentAsY();

        assertEquals(List.of("code"), columnsOf(1));
    }
}
