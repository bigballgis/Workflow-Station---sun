#!/usr/bin/env node
/**
 * sync-cursor-rules.mjs
 * --------------------------------------------------------------------------
 * Single source of truth = .cursor/rules (*.mdc)  AND  .cursor/skills/
 *
 * Generates native copies for:
 *   - Claude Code  → CLAUDE.md @import regions + .claude/skills/
 *   - GitHub Copilot → .github/copilot-instructions.md
 *                      + .github/instructions/*.instructions.md
 *                      + .github/skills/
 *   - Kiro         → .kiro/steering/*.md + .kiro/skills/
 *
 * Also:
 *   - Prunes generated orphans (no Cursor source) while preserving hand-written
 *     files that lack the AUTO-GENERATED marker / .synced-from-cursor stamp.
 *   - Single-instance lock (folderOpen + SessionStart may race).
 *
 * Routing (deterministic, mirrors Cursor's globs/alwaysApply semantics):
 *   globs contains deploy//Dockerfile/docker-compose/nginx/k8s -> deploy/CLAUDE.md
 *   else globs contains "frontend"                              -> frontend/CLAUDE.md
 *   else globs contains "backend"                               -> backend/CLAUDE.md
 *   else alwaysApply:false with globs                         -> matching directory bucket(s)
 *   else alwaysApply:false with no globs                      -> omitted (on-demand: skill / Cursor rule picker)
 *
 * Triggers: VS Code folderOpen task, Claude SessionStart, Copilot sessionStart,
 *           manual `node .claude/scripts/sync-cursor-rules.mjs`, CI drift check.
 *
 * No external deps. Cross-platform (Node 18+). Idempotent.
 */
import {
  readFileSync, writeFileSync, readdirSync, existsSync,
  mkdirSync, rmSync, statSync, unlinkSync,
} from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve, relative } from 'node:path';
import { tmpdir } from 'node:os';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..', '..');
const RULES_DIR = join(REPO, '.cursor', 'rules');
const CURSOR_SKILLS = join(REPO, '.cursor', 'skills');

const GEN_MARKER = 'AUTO-GENERATED by .claude/scripts/sync-cursor-rules.mjs';
const SKILL_STAMP = '.synced-from-cursor';
const LOCK_TTL_MS = 120_000;

const BEGIN = '<!-- BEGIN cursor-rules:auto -->';
const END = '<!-- END cursor-rules:auto -->';

const TARGETS = {
  root:         { file: join(REPO, 'CLAUDE.md'),                prefix: '@.cursor/rules/' },
  frontend:     { file: join(REPO, 'frontend', 'CLAUDE.md'),    prefix: '@../.cursor/rules/' },
  backend:      { file: join(REPO, 'backend', 'CLAUDE.md'),     prefix: '@../.cursor/rules/' },
  deploy:       { file: join(REPO, 'deploy', 'CLAUDE.md'),      prefix: '@../.cursor/rules/' },
  // 硬分叉进来的 Activepieces 子树（D12/D13）。上游自带的 CLAUDE.md / .claude / .agents 已删除，
  // 其中仍然成立的约定收进 .cursor/rules/activepieces-*.mdc，由本脚本落到这里。
  activepieces: { file: join(REPO, 'activepieces', 'CLAUDE.md'), prefix: '@../.cursor/rules/' },
};

const ROOT_PRIORITY = [
  'project-context', 'domain-model', 'reasoning-protocol',
  'ai-guardrails', 'cross-cutting', 'change-playbook', 'ai-development-playbook',
];

const SKILL_MIRRORS = [
  join(REPO, '.claude', 'skills'),
  join(REPO, '.github', 'skills'),
  join(REPO, '.kiro', 'skills'),
];

// ─── lock ───────────────────────────────────────────────────────────────────

function lockPath() {
  const gitLock = join(REPO, '.git', 'ai-guidance-sync.lock');
  return existsSync(join(REPO, '.git')) ? gitLock : join(tmpdir(), 'ws-ai-guidance-sync.lock');
}

function pidAlive(pid) {
  if (!pid || !Number.isFinite(pid)) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

function acquireLock() {
  const path = lockPath();
  if (existsSync(path)) {
    try {
      const prev = JSON.parse(readFileSync(path, 'utf8'));
      const age = Date.now() - (prev.ts || 0);
      if (age < LOCK_TTL_MS && pidAlive(prev.pid) && prev.pid !== process.pid) {
        console.log(`[sync-cursor-rules] another instance holds the lock (pid ${prev.pid}); skipping.`);
        return false;
      }
    } catch {
      // stale / corrupt lock — overwrite
    }
  }
  writeFileSync(path, JSON.stringify({ pid: process.pid, ts: Date.now() }));
  return true;
}

function releaseLock() {
  const path = lockPath();
  try {
    if (!existsSync(path)) return;
    const prev = JSON.parse(readFileSync(path, 'utf8'));
    if (prev.pid === process.pid) unlinkSync(path);
  } catch {
    // ignore
  }
}

// ─── frontmatter / body ─────────────────────────────────────────────────────

function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { fm: {}, body: text };
  const raw = m[1];
  const fm = {};
  const always = raw.match(/^alwaysApply:\s*(true|false)\s*$/m);
  if (always) fm.alwaysApply = always[1] === 'true';
  const globs = raw.match(/^globs:\s*(.+?)\s*$/m);
  if (globs) {
    fm.globs = globs[1].trim().replace(/^["']|["']$/g, '');
  }
  const desc = raw.match(/^description:\s*(.+?)\s*$/m);
  if (desc) fm.description = desc[1].trim().replace(/^["']|["']$/g, '');
  return { fm, body: text.slice(m[0].length).replace(/^\r?\n/, '') };
}

/** Split comma-separated globs without breaking brace groups. */
function splitGlobs(globs) {
  if (!globs) return [];
  const parts = [];
  let cur = '';
  let depth = 0;
  for (const ch of globs) {
    if (ch === '{') depth++;
    else if (ch === '}') depth = Math.max(0, depth - 1);
    if (ch === ',' && depth === 0) {
      const t = cur.trim();
      if (t) parts.push(t);
      cur = '';
    } else {
      cur += ch;
    }
  }
  const t = cur.trim();
  if (t) parts.push(t);
  return parts;
}

/**
 * Decide which CLAUDE.md bucket(s) a rule belongs to.
 * - alwaysApply:true -> root (always in context).
 * - alwaysApply:false with no globs -> omitted from CLAUDE.md (on-demand via skill / rule description).
 * - alwaysApply:false with globs -> route to matching directory bucket(s); cross-cutting globs
 *   with no path hint infer from file extensions.
 * Returns a de-duplicated array of bucket keys (may be empty).
 */
function classifyTargets(fm) {
  if (fm.alwaysApply === true) return ['root'];

  const globs = fm.globs;
  if (!globs) return [];

  const g = globs.toLowerCase();
  const targets = new Set();

  // activepieces 先判：它的 glob 里带 .ts，否则会被下面的兜底扫进 frontend。
  if (g.includes('activepieces')) targets.add('activepieces');
  if (/deploy\/|dockerfile|docker-compose|nginx|\/k8s|k8s\//.test(g)) targets.add('deploy');
  if (g.includes('frontend')) targets.add('frontend');
  if (g.includes('backend')) targets.add('backend');

  if (targets.size === 0) {
    if (/\bjava\b/.test(g)) targets.add('backend');
    if (/\b(ts|tsx|vue|scss)\b/.test(g)) targets.add('frontend');
  }

  if (targets.size === 0) targets.add('root');
  return [...targets];
}

function isAlwaysOn(fm) {
  return fm.alwaysApply === true || !fm.globs;
}

// ─── fs helpers ─────────────────────────────────────────────────────────────

function ensureDir(dir) {
  mkdirSync(dir, { recursive: true });
}

function writeIfChanged(absFile, content) {
  ensureDir(dirname(absFile));
  const cur = existsSync(absFile) ? readFileSync(absFile, 'utf8') : null;
  if (cur === content) return false;
  writeFileSync(absFile, content);
  return true;
}

function hasGenMarker(text) {
  return typeof text === 'string' && text.includes(GEN_MARKER);
}

function genBanner(sourceRel) {
  return [
    '<!--',
    `  ${GEN_MARKER}`,
    `  Source: ${sourceRel}`,
    '  DO NOT EDIT — change the Cursor source and re-run sync.',
    '-->',
    '',
  ].join('\n');
}

function listSkillDirs(root) {
  if (!existsSync(root)) return [];
  return readdirSync(root).filter((d) => {
    const p = join(root, d);
    try {
      return statSync(p).isDirectory() && existsSync(join(p, 'SKILL.md'));
    } catch {
      return false;
    }
  });
}

function copyDirShallow(srcDir, dstDir) {
  ensureDir(dstDir);
  let wrote = 0;
  for (const entry of readdirSync(srcDir)) {
    if (entry === SKILL_STAMP) continue;
    const s = join(srcDir, entry);
    const d = join(dstDir, entry);
    if (statSync(s).isDirectory()) {
      wrote += copyDirShallow(s, d);
      continue;
    }
    const src = readFileSync(s);
    const cur = existsSync(d) ? readFileSync(d) : null;
    if (!cur || !cur.equals(src)) {
      writeFileSync(d, src);
      wrote++;
    }
  }
  return wrote;
}

function loadRules() {
  if (!existsSync(RULES_DIR)) return [];
  return readdirSync(RULES_DIR)
    .filter((f) => f.endsWith('.mdc'))
    .sort()
    .map((f) => {
      const name = f.replace(/\.mdc$/, '');
      const abs = join(RULES_DIR, f);
      const text = readFileSync(abs, 'utf8');
      const { fm, body } = parseFrontmatter(text);
      return {
        name,
        file: f,
        sourceRel: `.cursor/rules/${f}`,
        fm,
        body,
        alwaysOn: isAlwaysOn(fm),
        globList: splitGlobs(fm.globs),
      };
    });
}

// ─── Claude: CLAUDE.md import regions ───────────────────────────────────────

function rewriteRegion(absFile, importLines) {
  if (!existsSync(absFile)) {
    console.warn(`[sync-cursor-rules] skip (missing): ${absFile}`);
    return false;
  }
  const src = readFileSync(absFile, 'utf8');
  const bi = src.indexOf(BEGIN);
  const ei = src.indexOf(END);
  if (bi === -1 || ei === -1 || ei < bi) {
    console.warn(`[sync-cursor-rules] skip (no managed region): ${absFile}`);
    return false;
  }
  const block = importLines.length
    ? `${BEGIN}\n${importLines.join('\n')}\n${END}`
    : `${BEGIN}\n${END}`;
  const next = src.slice(0, bi) + block + src.slice(ei + END.length);
  if (next !== src) {
    writeFileSync(absFile, next);
    return true;
  }
  return false;
}

function syncClaudeImports(rules) {
  const buckets = { root: [], frontend: [], backend: [], deploy: [], activepieces: [] };
  for (const rule of rules) {
    for (const target of classifyTargets(rule.fm)) {
      buckets[target].push(rule.name);
    }
  }

  buckets.root.sort((a, b) => {
    const ia = ROOT_PRIORITY.indexOf(a);
    const ib = ROOT_PRIORITY.indexOf(b);
    if (ia !== -1 || ib !== -1) {
      return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib) || a.localeCompare(b);
    }
    return a.localeCompare(b);
  });

  let changed = 0;
  for (const [key, names] of Object.entries(buckets)) {
    const { file, prefix } = TARGETS[key];
    const lines = names.map((n) => `${prefix}${n}.mdc`);
    if (rewriteRegion(file, lines)) changed++;
    console.log(`[sync-cursor-rules] claude/${key}: ${names.length} rule(s)` +
      (names.length ? ` -> ${names.join(', ')}` : ''));
  }
  console.log(`[sync-cursor-rules] claude: ${changed} CLAUDE.md file(s) updated.`);
}

// ─── Copilot instructions ───────────────────────────────────────────────────

function syncCopilotRules(rules) {
  const instrDir = join(REPO, '.github', 'instructions');
  ensureDir(instrDir);

  const always = rules.filter((r) => r.alwaysOn);
  const pathRules = rules.filter((r) => !r.alwaysOn);

  always.sort((a, b) => {
    const ia = ROOT_PRIORITY.indexOf(a.name);
    const ib = ROOT_PRIORITY.indexOf(b.name);
    if (ia !== -1 || ib !== -1) {
      return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib) || a.name.localeCompare(b.name);
    }
    return a.name.localeCompare(b.name);
  });

  const alwaysBody = [
    genBanner('.cursor/rules/*.mdc (alwaysApply)').trimEnd(),
    '',
    '# Workflow Station — Copilot repository instructions',
    '',
    '> Generated from Cursor always-on rules. Path-specific rules live in',
    '> `.github/instructions/*.instructions.md`. Skills: `.github/skills/`.',
    '> **Edit only** `.cursor/rules` / `.cursor/skills`, then re-run sync.',
    '',
    ...always.flatMap((r) => [
      `<!-- source: ${r.sourceRel} -->`,
      '',
      r.body.trimEnd(),
      '',
      '---',
      '',
    ]),
  ].join('\n').replace(/\n---\n\n$/u, '\n');

  let changed = 0;
  if (writeIfChanged(join(REPO, '.github', 'copilot-instructions.md'), alwaysBody)) {
    changed++;
  }

  const expected = new Set();
  for (const r of pathRules) {
    const outName = `${r.name}.instructions.md`;
    expected.add(outName);
    const applyTo = r.globList.join(',');
    const content = [
      '---',
      `applyTo: "${applyTo.replace(/"/g, '\\"')}"`,
      ...(r.fm.description ? [`description: "${r.fm.description.replace(/"/g, '\\"')}"`] : []),
      '---',
      '',
      genBanner(r.sourceRel).trimEnd(),
      '',
      r.body.trimEnd(),
      '',
    ].join('\n');
    if (writeIfChanged(join(instrDir, outName), content)) changed++;
  }

  // README for the instructions folder
  const readme = [
    genBanner('.cursor/rules').trimEnd(),
    '',
    '# Copilot path-specific instructions (generated)',
    '',
    'Do **not** edit these files by hand. Source: `.cursor/rules/*.mdc`.',
    'Always-on rules are aggregated in `../copilot-instructions.md`.',
    '',
  ].join('\n');
  if (writeIfChanged(join(instrDir, 'README.md'), readme)) changed++;
  expected.add('README.md');

  // Prune orphaned generated instruction files only
  if (existsSync(instrDir)) {
    for (const f of readdirSync(instrDir)) {
      if (!f.endsWith('.instructions.md') && f !== 'README.md') continue;
      if (expected.has(f)) continue;
      const abs = join(instrDir, f);
      if (!statSync(abs).isFile()) continue;
      const text = readFileSync(abs, 'utf8');
      if (!hasGenMarker(text)) {
        console.log(`[sync-cursor-rules] keep hand-written: .github/instructions/${f}`);
        continue;
      }
      unlinkSync(abs);
      console.log(`[sync-cursor-rules] pruned .github/instructions/${f}`);
      changed++;
    }
  }

  console.log(`[sync-cursor-rules] copilot rules: ${always.length} always + ${pathRules.length} path` +
    ` (${changed} file(s) touched)`);
}

// ─── Kiro steering ──────────────────────────────────────────────────────────

function syncKiroSteering(rules) {
  const steerDir = join(REPO, '.kiro', 'steering');
  ensureDir(steerDir);

  let changed = 0;
  const expected = new Set(['README.md']);

  for (const r of rules) {
    const outName = `${r.name}.md`;
    expected.add(outName);
    let fmBlock;
    if (r.alwaysOn) {
      fmBlock = ['---', 'inclusion: always', '---'].join('\n');
    } else {
      const patterns = r.globList;
      const patternYaml = patterns.length === 1
        ? `"${patterns[0].replace(/"/g, '\\"')}"`
        : `[${patterns.map((p) => `"${p.replace(/"/g, '\\"')}"`).join(', ')}]`;
      fmBlock = [
        '---',
        'inclusion: fileMatch',
        `fileMatchPattern: ${patternYaml}`,
        ...(r.fm.description ? [`description: "${r.fm.description.replace(/"/g, '\\"')}"`] : []),
        '---',
      ].join('\n');
    }
    const content = [
      fmBlock,
      '',
      genBanner(r.sourceRel).trimEnd(),
      '',
      r.body.trimEnd(),
      '',
    ].join('\n');
    if (writeIfChanged(join(steerDir, outName), content)) changed++;
  }

  const readme = [
    genBanner('.cursor/rules').trimEnd(),
    '',
    '# Kiro steering (generated)',
    '',
    'Do **not** edit these files by hand. Source: `.cursor/rules/*.mdc`.',
    'Hand-written steering files without the AUTO-GENERATED marker are preserved.',
    '',
  ].join('\n');
  if (writeIfChanged(join(steerDir, 'README.md'), readme)) changed++;

  for (const f of readdirSync(steerDir)) {
    if (!f.endsWith('.md')) continue;
    if (expected.has(f)) continue;
    const abs = join(steerDir, f);
    if (!statSync(abs).isFile()) continue;
    const text = readFileSync(abs, 'utf8');
    if (!hasGenMarker(text)) {
      console.log(`[sync-cursor-rules] keep hand-written: .kiro/steering/${f}`);
      continue;
    }
    unlinkSync(abs);
    console.log(`[sync-cursor-rules] pruned .kiro/steering/${f}`);
    changed++;
  }

  console.log(`[sync-cursor-rules] kiro steering: ${rules.length} file(s)` +
    ` (${changed} touched)`);
}

// ─── Skills mirror ──────────────────────────────────────────────────────────

function syncSkills() {
  if (!existsSync(CURSOR_SKILLS)) {
    console.warn('[sync-cursor-rules] no .cursor/skills dir; skipping skill mirror.');
    return;
  }
  const sourceSkills = listSkillDirs(CURSOR_SKILLS);
  // Do not mirror the README at skills root as a "skill"; only dirs with SKILL.md.
  // Also copy root README into each mirror as generated docs? Skip — per-target README below.

  for (const mirrorRoot of SKILL_MIRRORS) {
    ensureDir(mirrorRoot);
    let changed = 0;

    for (const name of sourceSkills) {
      const src = join(CURSOR_SKILLS, name);
      const dst = join(mirrorRoot, name);
      changed += copyDirShallow(src, dst);
      const stamp = join(dst, SKILL_STAMP);
      const stampBody = `${relative(REPO, src).replace(/\\/g, '/')}\n`;
      if (writeIfChanged(stamp, stampBody)) changed++;
    }

    // Prune only stamped (generated) skill dirs without Cursor source
    const sourceSet = new Set(sourceSkills);
    for (const name of listSkillDirs(mirrorRoot)) {
      const stamp = join(mirrorRoot, name, SKILL_STAMP);
      if (!existsSync(stamp)) {
        console.log(`[sync-cursor-rules] keep hand-written skill: ${relative(REPO, join(mirrorRoot, name))}`);
        continue;
      }
      if (!sourceSet.has(name)) {
        rmSync(join(mirrorRoot, name), { recursive: true, force: true });
        console.log(`[sync-cursor-rules] pruned ${relative(REPO, join(mirrorRoot, name))} (no .cursor source)`);
        changed++;
      }
    }

    const readmePath = join(mirrorRoot, 'README.md');
    const relMirror = relative(REPO, mirrorRoot).replace(/\\/g, '/');
    const readme = [
      genBanner('.cursor/skills').trimEnd(),
      '',
      `# ${relMirror} (generated mirror)`,
      '',
      'Do **not** edit by hand. Source of truth: `.cursor/skills/`.',
      'Hand-written skill directories without `.synced-from-cursor` are preserved.',
      '',
      `Mirrored skills: ${sourceSkills.join(', ') || '(none)'}`,
      '',
    ].join('\n');
    if (writeIfChanged(readmePath, readme)) changed++;

    console.log(`[sync-cursor-rules] skills → ${relMirror}: ${sourceSkills.length} mirrored` +
      ` (${changed} file(s) touched)`);
  }
}

// ─── main ───────────────────────────────────────────────────────────────────

function main() {
  if (!acquireLock()) {
    process.exitCode = 0;
    return;
  }
  try {
    if (!existsSync(RULES_DIR)) {
      console.warn('[sync-cursor-rules] no .cursor/rules dir; nothing to sync.');
      return;
    }
    const rules = loadRules();
    console.log(`[sync-cursor-rules] loaded ${rules.length} Cursor rule(s).`);

    syncClaudeImports(rules);
    syncCopilotRules(rules);
    syncKiroSteering(rules);
    syncSkills();

    console.log('[sync-cursor-rules] done.');
  } finally {
    releaseLock();
  }
}

main();
