#!/usr/bin/env node
// Generates metadata/pieces-seed.sql from metadata/*.json (fetched by fetch-pieces.sh).
// The seed is the DESIGNER half of a piece: rows in piece_metadata. The runtime half
// (the npm package) is baked into the AP image by prewarm-pieces.sh / Dockerfile.
// Idempotent: DELETE by (name, version) then INSERT, in one transaction.
// Apply:  docker exec -i platform-postgres-dev psql -U platform_dev -d workflow_platform_dev < metadata/pieces-seed.sql
'use strict'
const fs = require('fs')
const path = require('path')
const crypto = require('crypto')

const dir = path.join(__dirname, 'metadata')
const manifest = require('./pieces.json')

// Deterministic 21-char id (nanoid-shaped) from name@version, so re-running the
// generator never churns ids.
function pieceId(name, version) {
    return crypto.createHash('sha256').update(`${name}@${version}`).digest('base64url').slice(0, 21)
}

// Piece icons are mirrored into the AP web bundle by mirror-ap-cdn.mjs and served
// from AP's own origin: production is air-gapped (X-2/X-3) and cdn.activepieces.com
// is unreachable there, so every step icon would render broken. The mirror preserves
// the CDN path, hence a pure prefix swap. In-house pieces already carry a local path.
const CDN_PREFIX = 'https://cdn.activepieces.com/'
const LOCAL_PREFIX = '/ap-cdn/'

function localizeLogoUrl(logoUrl) {
    if (!logoUrl) return ''
    if (!logoUrl.startsWith(CDN_PREFIX)) return logoUrl
    return LOCAL_PREFIX + logoUrl.slice(CDN_PREFIX.length)
}

// Dollar-quote instead of escaping: piece JSON is full of quotes/backslashes.
function lit(value) {
    if (value === null || value === undefined) return 'NULL'
    const s = typeof value === 'string' ? value : JSON.stringify(value)
    if (s.includes('$ap$')) throw new Error('value contains $ap$ delimiter')
    return `$ap$${s}$ap$`
}

function textArray(arr) {
    if (!Array.isArray(arr)) return `'{}'::varchar[]`
    if (arr.length === 0) return `'{}'::varchar[]`
    return `ARRAY[${arr.map(lit).join(', ')}]::varchar[]`
}

const lines = [
    '-- GENERATED by deploy/pieces/generate-metadata-seed.js — do not edit by hand.',
    '-- Piece allowlist seed for piece_metadata (with AP_PIECES_SYNC_MODE=NONE, AP serves ONLY these).',
    'BEGIN;',
]

for (const { name, version } of manifest) {
    const short = name.split('/')[1]
    const m = JSON.parse(fs.readFileSync(path.join(dir, `${short}.json`), 'utf8'))
    if (m.name !== name || m.version !== version) {
        throw new Error(`metadata/${short}.json is ${m.name}@${m.version}, expected ${name}@${version} — re-run fetch-pieces.sh`)
    }
    lines.push(`DELETE FROM piece_metadata WHERE name = ${lit(name)} AND version = ${lit(version)};`)
    lines.push(
        'INSERT INTO piece_metadata (id, created, updated, "name", "displayName", "logoUrl", description, "version",',
        '  "minimumSupportedRelease", "maximumSupportedRelease", actions, triggers, auth, "pieceType", "packageType",',
        '  "archiveId", "platformId", categories, authors, "projectUsage", i18n)',
        `VALUES (${[
            lit(pieceId(name, version)),
            // Self-developed pieces carry no upstream publish date. Falling back to epoch 0 put
            // "1969/12/31" in the Admin Center piece list — a wrong date reads as broken data,
            // whereas the seed time is both truthful (that IS when this catalog row appeared)
            // and stable, since each seed run DELETEs and re-INSERTs the row.
            m.created ? lit(m.created) : 'now()',
            m.updated ? lit(m.updated) : 'now()',
            lit(name),
            lit(m.displayName ?? short),
            lit(localizeLogoUrl(m.logoUrl)),
            lit(m.description ?? ''),
            lit(version),
            lit(m.minimumSupportedRelease ?? '0.0.0'),
            lit(m.maximumSupportedRelease ?? '99999.99999.9999'),
            lit(m.actions ?? {}),
            lit(m.triggers ?? {}),
            m.auth ? lit(m.auth) : 'NULL',
            lit('OFFICIAL'),
            lit('REGISTRY'),
            'NULL',
            'NULL',
            textArray(m.categories),
            textArray(m.authors),
            '0',
            m.i18n ? lit(m.i18n) : 'NULL',
        ].join(',\n        ')});`,
    )
}

lines.push('COMMIT;', '')
const out = path.join(dir, 'pieces-seed.sql')
fs.writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out} (${manifest.length} pieces)`)
